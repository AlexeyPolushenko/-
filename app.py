import streamlit as st

#В терминал для запуска
# streamlit run app.py

# НАСТРОЙКА: Правильные ответы (пишите в нижнем регистре для надежности)
RIGHT_WIFE_NAME = "тома"  # Имя жены
RIGHT_BDAY = "23.08"  # ДР в формате ДД.ММ.ГГГГ (или просто число)
RIGHT_child1 = "лёша"  # Кличка кота/собаки или любой другой секретный вопрос
RIGHT_child2 = "юля"
RIGHT_child3 = "костя"
RIGHT_car = "бмв"


# Инициализация состояния авторизации (чтобы сайт помнил, что папа вошел)
if "authenticated" not in st.session_state:
    st.session_state["authenticated"] = False

# --- ТЕСТ-ПРОГРАММА (Экран авторизации) ---
if not st.session_state["authenticated"]:
    st.title("🛑 СТОП! ЗОНА ПОВЫШЕННОГО СЕКРЕТА")
    st.subheader("Требуется пройдите сатирическую верификацию личности:")

    st.write("Система должна убедиться, что вы — это вы, а не шпион, претендующий на праздничный торт :)")

    # Вопрос 1
    wife_input = st.text_input("1. Как зовут вашу законную супругу и по совместительству главную женщину в доме?",
                               placeholder="Имя").strip().lower()

    # Вопрос 2
    bday_input = st.text_input("2. Дата вашего рождения (в формате ДД.ММ, чтобы проверить вашу память):",
                               placeholder="__.__").strip().lower()

    # Вопрос 3
    child1_input = st.text_input(
        "3. Как зовут того, кто заставил вас проходить этот тест?",
        placeholder="Имя").strip().lower()

    # Вопрос 4
    child2_input = st.text_input(
        "4. Как зовут ту, которая имеет самые длинные волосы среди Полющенков?",
        placeholder="Имя").strip().lower()

    # Вопрос 5
    child3_input = st.text_input(
        "5. Как зовут того, кто у нас самый маленький, но самый активный?",
        placeholder="Имя").strip().lower()

    # Вопрос 5
    car_input = st.text_input(
        "6. Какая твоя любимая марка машины (название на русском)?",
        placeholder="Марка").strip().lower()



    # Кнопка проверки
    if st.button("ПОЛУЧИТЬ ДОСТУП К ПОЗДРАВЛЕНИЮ"):
        if wife_input == RIGHT_WIFE_NAME and bday_input == RIGHT_BDAY and child1_input == RIGHT_child1 and child2_input == RIGHT_child2 and child3_input == RIGHT_child3 and car_input == RIGHT_car:
            st.session_state["authenticated"] = True
            st.rerun()  # Перезагружаем страницу, чтобы показать поздравление
        else:
            st.error("❌ ДОСТУП ЗАПРЕЩЕН! Ответы неверны. Попробуйте еще раз или подкупите создателя сайта.")

# --- ОСНОВНОЙ САЙТ (Экран поздравления) ---
else:
    # Кнопка "Выйти" на случай, если захочется протестировать заново
    if st.sidebar.button("Заблокировать сайт обратно"):
        st.session_state["authenticated"] = False
        st.rerun()

    # Праздничный контент
    st.balloons()  # Визуальный эффект: запускает воздушные шары по всему экрану!

    st.title("🎉 С ДНЕМ РОЖДЕНИЯ, ПАПА! 🎂")
    st.subheader("Личность успешно подтверждена. Добро пожаловать на твоё поздравление!")

    st.write("---")

    # Сюда можно вставить любой текст поздравления
    st.markdown("""
    ### Самый лучший отец в мире! ❤️
    Мы тебя очень любим и хотим пожелать тебе:
    * **Живота**, чтобы у тебя не было) .
    * **Нервов** тебе прочнее стали.
    * **Улыбок** каждый день и побольше поводов для радости!
    * **Возможностей** тебе безграниц.
    """)

    # Примеры того, что еще можно легко добавить:
